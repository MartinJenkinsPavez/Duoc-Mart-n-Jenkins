CREATE OR REPLACE VIEW VW_AUM_MEDICO_X_CARGO AS
SELECT
    TO_CHAR(m.rut_med, 'FM09G999G999') || '-' || m.dv_run AS RUT_MEDICO,
    c.nombre AS CARGO,
    m.sueldo_base AS SUELDO_ACTUAL,
    ROUND(m.sueldo_base * 1.15) AS SUELDO_AUMENTADO
FROM
    SYN_MEDICO m
JOIN
    SYN_CARGO c ON m.car_id = c.car_id
WHERE
    LOWER(c.nombre) LIKE '%atención%' OR LOWER(c.nombre) LIKE '%atencion%'
ORDER BY
    ROUND(m.sueldo_base * 1.15) DESC;
    
