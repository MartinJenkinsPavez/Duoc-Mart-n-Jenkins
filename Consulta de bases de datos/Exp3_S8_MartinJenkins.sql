CREATE OR REPLACE VIEW VW_RECALCULO_COSTOS AS
SELECT
    TO_CHAR(p.pac_run, 'FM99G999G999') || '-' || p.dv_run AS RUT_PACIENTE,
    p.apaterno || ' ' || p.amaterno || ' ' || p.pnombre AS NOMBRE_PACIENTE,
    s.descripcion AS SISTEMA_SALUD,
    '$' || TO_CHAR(bc.costo, 'FM999G999') AS COSTO,
    bc.hr_consulta AS HORARIO_ATENCION,
    TO_CHAR(bc.fecha_bono, 'MM-YYYY') AS FECHA_CONSULTA,
    '$' || TO_CHAR(
        CASE
            WHEN bc.costo BETWEEN 15000 AND 25000 THEN ROUND(bc.costo * 1.15)
            WHEN bc.costo > 25000 THEN ROUND(bc.costo * 1.20)
            ELSE bc.costo
        END, 'FM999G999'
    ) AS REAJUSTE
FROM
    SYN_BONO_CONSULTA bc
JOIN
    SYN_PACIENTE p ON bc.pac_run = p.pac_run
JOIN
    SYN_SALUD s ON p.sal_id = s.sal_id
WHERE
    EXTRACT(YEAR FROM bc.fecha_bono) = EXTRACT(YEAR FROM SYSDATE) - 1
    AND bc.hr_consulta > '17:15'
    AND p.sal_id IN (
        SELECT sa.sal_id
        FROM SYN_SALUD sa
        JOIN SYN_SISTEMA_SALUD ss ON sa.tipo_sal_id = ss.tipo_sal_id
        WHERE UPPER(ss.descripcion) LIKE '%ISAPRE%' 
           OR UPPER(ss.descripcion) LIKE '%FONASA%'
    )
ORDER BY
    bc.fecha_bono ASC,
    p.pac_run ASC
WITH READ ONLY;